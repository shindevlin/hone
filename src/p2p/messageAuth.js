/**
 * Entry types that may be gossiped via MEMPOOL_ENTRY.
 * These are user-initiated actions that need propagation before block inclusion.
 */
const MEMPOOL_ALLOWED_TYPES = [
  "TRANSFER",
  "ACCOUNT_CREATE",
  "STAKE",
  "UNSTAKE",
  "ESCROW_LOCK",
  "ESCROW_RELEASE",
  "ESCROW_REFUND",
  "STORE_OPEN",
  "PRODUCT_CREATE",
  "ORDER_PLACE",
  "SERVICE_DEPLOY",
  "SERVICE_HEARTBEAT",
  "STORAGE_HEARTBEAT",
  "BLOB_STORE_COMMIT",
  "ORACLE_REPORT",
  "SENSOR_READING",
  "SNAPSHOT_COMMIT",
  "BRIDGE_WRAP",
  "BRIDGE_UNWRAP",
];

/**
 * Entry types that are generated by chain authority — must only arrive inside
 * EPOCH_FINALIZED block payloads. Receiving one via MEMPOOL_ENTRY is an attack.
 */
const BLOCK_ONLY_TYPES = [
  "MINING_REWARD",
  "FAUCET",
  "CLOCK_REWARD",
  "STORAGE_REWARD",
  "SERVICE_REWARD",
  "IOT_REWARD",
];

module.exports = {
  REQUIRE_SIGNATURES,
  hashMessageData,
  signMessage,
  verifyMessage,
  verifyAccountSignature,
  MEMPOOL_ALLOWED_TYPES,
  BLOCK_ONLY_TYPES,
};
